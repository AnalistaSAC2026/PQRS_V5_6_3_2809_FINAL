import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {createHash} from "node:crypto";
import {dirname,join} from "node:path";
import {fileURLToPath} from "node:url";
import vm from "node:vm";

const root=join(dirname(fileURLToPath(import.meta.url)),"..");
const read=name=>readFileSync(join(root,name),"utf8");
const hash=name=>createHash("sha256").update(readFileSync(join(root,name))).digest("hex").toUpperCase();
const app=read("app.js"),html=read("index.html"),css=read("styles.css");
const expectedHash="CA4E224D19E3B45D50DC86CB336D5233D075E3CA12D16BFF16F9DCE6E278BD82";
const context={window:{}};
vm.runInNewContext(read("data.js"),context);
const snapshot=context.window.PQRS_BOOTSTRAP;
const d=snapshot.dicts;
const tracking=snapshot.records.map(r=>({year:d.year[r[0]],month:d.month[r[1]],country:d.country[r[2]],classification:d.classification[r[3]],area:d.area[r[4]],state:d.state[r[5]],openDays:r[6],responsible:d.responsible[r[13]]})).filter(r=>r.state!=="Cerrada"&&Number(r.openDays)>0&&String(r.responsible||"").trim()!=="");
const areas=[...new Set(snapshot.records.map(r=>d.area[r[4]]).filter(Boolean))].sort();
const byArea=Object.fromEntries(areas.map(area=>[area,tracking.filter(r=>r.area===area)]));
const metrics=rows=>({total:rows.length,r15:rows.filter(r=>r.openDays>=1&&r.openDays<=5).length,r610:rows.filter(r=>r.openDays>=6&&r.openDays<=10).length,r1115:rows.filter(r=>r.openDays>=11&&r.openDays<=15).length,r16:rows.filter(r=>r.openDays>=16).length,responsibles:new Set(rows.map(r=>r.responsible)).size});

assert.equal(hash("data.js"),expectedHash,"data.js cambió");
assert.equal(snapshot.meta.cutoff,"28/09/2026");
assert.ok(app.includes('case "tracking": renderTracking()'));
assert.ok(app.includes('["area","Área"]'));
assert.ok(app.includes("state.trackingFilters.area"));
assert.ok(app.includes("function getFilterSet(field)"));
assert.ok(app.includes("function setFilterSet(field,values)"));
assert.ok(app.includes('new Set(button.dataset.filterAction==="all"?filterValues(field):[])'));
assert.ok(app.includes("restoreOpenFilter(f)"));
assert.ok(app.includes('state.trackingFilters.area=new Set(areas)'));
assert.ok(app.includes('getFilterSet("area").has(r.area)'));
assert.ok(app.includes('getFilterSet("year").has(r.year)'));
assert.ok(app.includes('getFilterSet("month").has(r.month)'));
assert.ok(app.includes('getFilterSet("country").has(r.country)'));
assert.ok(app.includes('getFilterSet("classification").has(r.classification)'));
for(const label of ["Casos seguimiento","1–5 días","6–10 días","11–15 días","16+ días","Responsables"]) assert.ok(app.includes(label));
assert.ok(app.includes("const rows=getTrackingRows()"));
assert.ok(app.includes("getTrackingDetail(normalized)"));
assert.ok(app.includes("visibleTrackingDetailRows()"));
assert.ok(app.includes("exportTrackingDetailCSV"));
assert.ok(app.includes('Área: ${area}'));
assert.ok(app.includes("renderActiveFilterSummary"));
assert.ok(app.includes('state.trackingFilters.area=new Set(unique("area"))'));
assert.ok(html.includes('id="filterMobileDrawer"'));
assert.ok(css.includes("prefers-color-scheme:dark"));
assert.ok(app.includes("function renderMotives()"));
assert.ok(app.includes("Causa raíz comercial"));
assert.ok(!html.includes('data-view="b2b"'));
assert.equal(areas.reduce((sum,area)=>sum+byArea[area].length,0),tracking.length,"La suma por áreas no concilia");
for(const area of areas) assert.deepEqual(metrics(byArea[area]),metrics(tracking.filter(row=>row.area===area)),`No concilia ${area}`);
assert.equal(metrics([]).total,0,"La selección vacía debe producir cero resultados");
const combined=tracking.filter(row=>["Comercial","Sac"].includes(row.area));
assert.equal(combined.length,(byArea.Comercial?.length||0)+(byArea.Sac?.length||0),"Comercial + SAC no concilia");
console.log(JSON.stringify({status:"PASS",version:"PQRS V5.6.4 · Tracking Area Filter",checks:32,cutoff:snapshot.meta.cutoff,areas,trackingTotal:tracking.length,byArea:Object.fromEntries(areas.map(area=>[area,metrics(byArea[area])])),dataHash:hash("data.js")},null,2));
